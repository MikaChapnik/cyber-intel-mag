def _dek(desc: str) -> str:
    """build.py truncates descriptions at ~160 chars; end them on a sentence or a word."""
    desc = html.unescape(desc).strip()
    if not desc or desc[-1] in ".!?\"'”’":
        return desc
    cut = max(desc.rfind(". "), desc.rfind("? "), desc.rfind("! "))
    if cut > 60:
        return desc[:cut + 1]
    return desc.rsplit(" ", 1)[0].rstrip(",;:-–—") + "…"


def load_articles(site: Path):
    out = []
    for p in (site / "articles").glob("*.html"):
        s = p.read_text(encoding="utf-8")
        m = re.search(r'<script type="application/ld\+json">(.*?)</script>', s, re.S)
        try:
            ld = json.loads(m.group(1)) if m else {}
        except ValueError:
            continue
        date = ld.get("datePublished", "")
        if ld.get("@type") != "NewsArticle" or not re.match(r"\d{4}-\d\d-\d\d", date):
            continue  # undated legacy imports never reach the front page
        kw = [k.strip() for k in ld.get("keywords", "").split(",") if k.strip()]
        y, mo, d = int(date[:4]), int(date[5:7]), int(date[8:10])
        mins = re.search(r"(\d+) min read", s)
        out.append({
            "url": f"{ROOT}/articles/{p.name}", "date": date,
            "short": f"{d:02d} {MONTHS[mo - 1]}", "long": f"{d} {MONTHS[mo - 1]} {y}",
            "title": html.unescape(ld.get("headline", "")).strip(),
            "dek": _dek(ld.get("description", "")),
            "author": (ld.get("author") or {}).get("name", "Cyber Brief Daily"),
            "cat": ld.get("articleSection") or (kw[0] if kw else "News"),
            "kw": kw, "image": ld.get("image", ""),
            "read": f"{mins.group(1)} min read" if mins else "",
            "desks": [name for name, keys in DESKS.items() if keys & set(kw)],
        })
    out.sort(key=lambda a: a["date"], reverse=True)
    return out


MONO = "font-family:'Geist Mono',monospace;font-size:11px;text-transform:uppercase;letter-spacing:0.06em;color:#b8321f"


def _hero(a):
    e = html.escape
    second = next((k for k in a["kw"] if k not in (a["cat"], "News")), "")
    img = (f'<a href="{a["url"]}" style="display:block;aspect-ratio:16/9;overflow:hidden;background:#e6e2d8">'
           f'<img src="{e(a["image"])}" alt="{e(a["title"])}" style="width:100%;height:100%;object-fit:cover;display:block"></a>'
           if a["image"] else "")
    meta = [f'<span style="color:#17171a;font-weight:500">{e(a["author"])}</span>', f'<span>{a["long"]}</span>']
    if a["read"]:
        meta.append(f'<span>{a["read"]}</span>')
    return f"""<article style="flex:2 1 520px;min-width:0;padding-right:32px;display:flex;flex-direction:column;gap:18px">
    {img}
    <div style="display:flex;gap:12px;align-items:center;font-family:'Geist Mono',monospace;font-size:11.5px;text-transform:uppercase;letter-spacing:0.06em">
      <span style="color:#b8321f;font-weight:500">{e(a["cat"])}</span>
      <span style="color:#8d8a83">{e(second)}</span>
    </div>
    <h1 style="margin:0;font-family:'Newsreader',serif;font-weight:500;font-size:clamp(34px,4.2vw,52px);line-height:1.02;letter-spacing:-0.02em;text-wrap:balance"><a href="{a["url"]}">{e(a["title"])}</a></h1>
    <p style="margin:0;font-family:'Newsreader',serif;font-size:20px;line-height:1.45;color:#3a3935;max-width:62ch;text-wrap:pretty">{e(a["dek"])}</p>
    <div style="display:flex;gap:10px;align-items:center;font-size:13px;color:#5c5a55">
      {'<span>·</span>'.join(meta)}
    </div>
  </article>"""


def _side(items):
    e = html.escape
    pads = ["padding-bottom:22px;border-bottom:1px solid #d6d2c8", "padding:22px 0;border-bottom:1px solid #d6d2c8", "padding-top:22px"]
    rows = []
    for a, pad in zip(items, pads):
        dek = f'\n      <p style="margin:0;font-size:14.5px;line-height:1.5;color:#4a4843">{e(a["dek"])}</p>' if a["dek"] and pad != pads[2] else ""
        rows.append(f"""    <article style="{pad};display:flex;flex-direction:column;gap:10px">
      <span style="{MONO}">{e(a["cat"])}</span>
      <h2 style="margin:0;font-family:'Newsreader',serif;font-weight:500;font-size:25px;line-height:1.12;letter-spacing:-0.01em;text-wrap:balance"><a href="{a["url"]}">{e(a["title"])}</a></h2>{dek}
      <span style="font-size:12.5px;color:#5c5a55">{e(a["author"])} · {a["short"]}</span>
    </article>""")
    return "\n".join(rows)


def _latest(pool):
    """Every row that is in the top 8 of at least one filter; data-show lists those filters."""
    e = html.escape
    show = {}
    for f in ["All"] + list(DESKS):
        for a in [a for a in pool if f == "All" or f in a["desks"]][:8]:
            show.setdefault(a["url"], []).append(f)
    rows = []
    for a in pool:
        if a["url"] not in show:
            continue
        hidden = "" if "All" in show[a["url"]] else " hidden"
        rows.append(f"""<article data-show="|{'|'.join(show[a['url']])}|"{hidden} style="display:grid;grid-template-columns:84px minmax(0,1fr);gap:20px;padding:20px 0;border-bottom:1px solid #d6d2c8">
          <div style="display:flex;flex-direction:column;gap:4px;font-family:'Geist Mono',monospace;font-size:11.5px;color:#5c5a55;padding-top:5px">
            <span style="color:#17171a">{a["short"]}</span>
          </div>
          <div style="display:flex;flex-direction:column;gap:7px">
            <span style="{MONO}">{e(a["cat"])}</span>
            <h3 style="margin:0;font-family:'Newsreader',serif;font-weight:500;font-size:23px;line-height:1.15;letter-spacing:-0.01em;text-wrap:balance"><a href="{a["url"]}">{e(a["title"])}</a></h3>
            <p style="margin:0;font-size:14.5px;line-height:1.5;color:#4a4843;max-width:68ch;text-wrap:pretty">{e(a["dek"])}</p>
            <span style="font-size:12.5px;color:#5c5a55">{e(a["author"])}</span>
          </div>
        </article>""")
    return "\n".join(rows)


def build_homepage(site: Path, home: str) -> str:
    arts = load_articles(site)
    if len(arts) < 12:
        print(f"  homepage: only {len(arts)} dated articles found, keeping the template as-is")
        return home
    hero, side, rest = arts[0], arts[1:4], arts[4:]

    home = re.sub(r'<article style="flex:2 1 520px.*?</article>', lambda _: _hero(hero), home, count=1, flags=re.S)
    home = re.sub(r'(<div style="flex:1 1 260px;min-width:0;padding:0 28px[^"]*">).*?(</div>\s*<aside)',
                  lambda m: m.group(1) + "\n" + _side(side) + "\n  " + m.group(2), home, count=1, flags=re.S)
    home = re.sub(r'(<section data-screen-label="Latest".*?<div style="display:flex;flex-direction:column">).*?'
                  r'(</div>\s*<a href="https://cyberbriefdaily\.com/categories/news\.html" style="display:inline-flex)',
                  lambda m: m.group(1) + "\n" + _latest(rest) + "\n    " + m.group(2), home, count=1, flags=re.S)

    # desk counts, straight from the category pages
    for name, slug in DESK_PAGES:
        cat = site / "categories" / f"{slug}.html"
        m = re.search(r'class="cat-count-text">(\d+)', cat.read_text(encoding="utf-8")) if cat.exists() else None
        if m:
            home = re.sub(rf'(<span>{re.escape(html.escape(name))}</span><span[^>]*>)\d+(</span>)',
                          lambda x: x.group(1) + m.group(1) + x.group(2), home)

    # social image + structured data follow the lead story
    if hero["image"]:
        home = re.sub(r'(<meta (?:property="og:image"|name="twitter:image") content=")[^"]*', lambda m: m.group(1) + hero["image"], home)
        home = re.sub(r'(<link rel="preload" as="image" href=")[^"]*', lambda m: m.group(1) + hero["image"], home)
    items = [{"@type": "ListItem", "position": i + 1, "url": a["url"], "name": a["title"]} for i, a in enumerate(arts[:8])]
    def fix_ld(m):
        ld = json.loads(m.group(1))
        for node in ld.get("@graph", []):
            if node.get("@type") == "ItemList":
                node["itemListElement"] = items
        return f'<script type="application/ld+json">{json.dumps(ld, ensure_ascii=False)}</script>'
    home = re.sub(r'<script type="application/ld\+json">(.*?)</script>', fix_ld, home, count=1, flags=re.S)

    # filter script: rows carry the filters they belong to
    home = re.sub(r"rows=document\.querySelectorAll\('article\[data-desk\]'\)", "rows=document.querySelectorAll('article[data-show]')", home)
    home = re.sub(r"r\.hidden = f==='All' \? \+r\.getAttribute\('data-rank'\)>=8 : r\.getAttribute\('data-desk'\)!==f;",
                  "r.hidden = r.getAttribute('data-show').indexOf('|'+f+'|')<0;", home)
    print(f"  homepage: lead = {hero['title']!r} ({hero['long']})")
    return home


def swap_fonts_and_colors(text: str) -> str:
    for old, new in FONT_MAP.items():
        text = re.sub(rf"""(['"]){re.escape(old)}\1""", rf"\1{new}\1", text)
    for old, new in COLOR_MAP.items():
        text = re.sub(re.escape(old), new, text, flags=re.I)
    return text


def restyle_page(path: Path, header: str, footer: str) -> bool:
    s = path.read_text(encoding="utf-8")
    orig = s
    s = V2_HEADER.sub(lambda _: header, s) if V2_HEADER.search(s) else OLD_HEADER.sub(lambda _: header, s, count=1)
    s = V2_FOOTER.sub(lambda _: footer, s) if V2_FOOTER.search(s) else OLD_FOOTER.sub(lambda _: footer, s, count=1)
    s = OLD_FONTS.sub(FONTS_LINK, s)
    prefix = "../" * (len(path.relative_to(SITE).parts) - 1) or "./"
    theme = f'<link rel="stylesheet" href="{prefix}css/theme-v2.css">'
    if "css/theme-v2.css" not in s:
        s = re.sub(r'(<link rel="stylesheet" href="[^"]*css/style\.css">)', lambda m: m.group(1) + "\n" + theme, s, count=1)
    # page-level <style> blocks
    s = re.sub(r"<style>.*?</style>", lambda m: swap_fonts_and_colors(m.group(0)), s, flags=re.S)
    if s != orig:
        path.write_text(s, encoding="utf-8", newline="\n")
        return True
    return False


def main():
    if not (SITE / "css" / "style.css").exists():
        sys.exit(f"Not a built site: {SITE}")
    home = HOMEPAGE.read_text(encoding="utf-8")
    header, footer = chrome_from_homepage(home)

    (SITE / "index.html").write_text(build_homepage(SITE, home), encoding="utf-8", newline="\n")

    css = SITE / "css" / "style.css"
    css.write_text(swap_fonts_and_colors(css.read_text(encoding="utf-8")), encoding="utf-8", newline="\n")
    (SITE / "css" / "theme-v2.css").write_text(THEME_CSS, encoding="utf-8", newline="\n")

    pages = [p for p in SITE.rglob("*.html")
             if p.relative_to(SITE).as_posix() not in SKIP
             and not any(part.startswith(".") for part in p.relative_to(SITE).parts)]
    changed = sum(restyle_page(p, header, footer) for p in pages)
    missing = [p.relative_to(SITE).as_posix() for p in pages if "cbd-v2:header" not in p.read_text(encoding="utf-8")]
    print(f"restyle: homepage restored, {changed}/{len(pages)} pages updated")
    if missing:
        print(f"  WARNING: {len(missing)} pages have no recognisable header: {missing[:5]}")


if __name__ == "__main__":
    main()
