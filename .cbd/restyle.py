def chrome_from_homepage(home: str):
    """Cut the header and footer out of the homepage so every page stays in sync with it."""
    start = home.index("<!-- Utility bar -->")
    end = home.index("</header>", start) + len("</header>")
    header = home[start:end]
    footer = re.search(r"<footer.*?</footer>", home, re.S).group(0)
    # links that only resolve on the homepage
    header = header.replace('href="#newsletter"', 'href="https://cyberbriefdaily.com/#newsletter"')
    # slightly smaller masthead on inner pages
    header = header.replace("font-size:clamp(40px,6vw,68px)", "font-size:clamp(34px,4.6vw,52px)")
    header = (f'<!-- cbd-v2:header --><div class="cbd-chrome" id="top" style="font-family:\'Geist\',system-ui,sans-serif">'
              f'{header}</div>{TODAY_JS}<!-- /cbd-v2:header -->')
    footer = (f'<!-- cbd-v2:footer --><div class="cbd-chrome" style="font-family:\'Geist\',system-ui,sans-serif;margin-top:56px">'
              f'{footer}</div><!-- /cbd-v2:footer -->')
    return header, footer


